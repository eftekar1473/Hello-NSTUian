async function syncDepartments() {
  console.log('Starting Department Synchronization for 33 NSTU Departments...');

  // Step 1: Fetch existing departments
  const existing = await prisma.department.findMany();
  console.log(`Found ${existing.length} existing departments in database.`);

  // Mapping existing department names/abbrs to new code target
  const existingMapping = [
    { match: (d) => d.department_code === '04' || d.name.toLowerCase().includes('bangla'), targetCode: '26' },
    { match: (d) => d.department_code === '02' || d.name.toLowerCase().includes('math'), targetCode: '06' },
    { match: (d) => d.department_code === '14' || d.name.toLowerCase().includes('english'), targetCode: '07' },
    { match: (d) => d.department_code === '03' || d.name.toLowerCase().includes('physics'), targetCode: '31' },
    { match: (d) => d.department_code === '06' || d.name.toLowerCase().includes('chem') && !d.name.toLowerCase().includes('applied'), targetCode: '32' },
    { match: (d) => d.department_code === '25' || d.abbreviation === 'IIT' || d.name.toLowerCase().includes('information technology'), targetCode: '25' },
    { match: (d) => d.department_code === '01' || d.name.toLowerCase().includes('applied chemistry'), targetCode: '04' },
    { match: (d) => d.department_code === '05' || d.name.toLowerCase().includes('biotechnology'), targetCode: '13' },
    { match: (d) => d.department_code === '11' || d.abbreviation === 'CSTE' || d.name.toLowerCase().includes('telecommunication'), targetCode: '01' },
    { match: (d) => d.department_code === '12' || d.abbreviation === 'EEE' || d.name.toLowerCase().includes('electrical'), targetCode: '17' },
    { match: (d) => d.department_code === '15' || d.abbreviation === 'FIMS' || d.name.toLowerCase().includes('fisheries'), targetCode: '02' },
    { match: (d) => d.department_code === '26' || d.abbreviation === 'MICRO' || d.name.toLowerCase().includes('microbiology'), targetCode: '05' },
    { match: (d) => d.department_code === '28' || d.abbreviation === 'PHARM' || d.name.toLowerCase().includes('pharmacy'), targetCode: '03' },
    { match: (d) => d.department_code === '19' || d.name.toLowerCase().includes('education') && !d.name.toLowerCase().includes('administration'), targetCode: '19' },
    { match: (d) => d.department_code === '30' || d.abbreviation === 'SE' || d.name.toLowerCase().includes('social work'), targetCode: '30' },
  ];

  // Assign temporary codes first to prevent unique constraint collisions
  for (const dept of existing) {
    await prisma.department.update({
      where: { id: dept.id },
      data: { department_code: `TEMP-${dept.id.substring(0, 8)}` },
    });
  }
  console.log('Temporary codes assigned to avoid collision.');

  // Now update matched existing departments to their target definition
  const updatedTargetCodes = new Set();
  for (const dept of existing) {
    const foundMap = existingMapping.find((m) => m.match(dept));
    if (foundMap) {
      const targetDef = DEPARTMENTS_33.find((d) => d.department_code === foundMap.targetCode);
      if (targetDef) {
        await prisma.department.update({
          where: { id: dept.id },
          data: {
            department_code: targetDef.department_code,
            name: targetDef.name,
            abbreviation: targetDef.abbreviation,
            description: targetDef.description,
            icon_url: targetDef.icon_url,
            is_active: true,
          },
        });
        updatedTargetCodes.add(targetDef.department_code);
        console.log(`Updated existing department ${dept.name} -> [${targetDef.department_code}] ${targetDef.name}`);
      }
    }
  }

  // Create remaining departments from the 33 list
  for (const def of DEPARTMENTS_33) {
    if (updatedTargetCodes.has(def.department_code)) {
      continue;
    }

    const createdDept = await prisma.department.create({
      data: {
        department_code: def.department_code,
        name: def.name,
        abbreviation: def.abbreviation,
        description: def.description,
        icon_url: def.icon_url,
        is_active: true,
      },
    });

    // Create academic program & 8 semesters
    const progCode = def.abbreviation ? def.abbreviation.replace(/[^A-Z0-9]/gi, '') : def.department_code;
    const program = await prisma.academicProgram.create({
      data: {
        department_id: createdDept.id,
        program_name: `Bachelor of Science in ${def.name}`,
        program_code: `BS-${progCode}`,
      },
    });

    for (let sem = 1; sem <= 8; sem++) {
      await prisma.semester.create({
        data: {
          program_id: program.id,
          semester_number: sem,
          semester_name: `Semester ${sem}`,
        },
      });
    }

    console.log(`Created new department [${def.department_code}] ${def.name} with 8 semesters.`);
  }

  // Double check any leftover TEMP- departments
  const leftoverTemp = await prisma.department.findMany({
    where: { department_code: { startsWith: 'TEMP-' } },
  });
  if (leftoverTemp.length > 0) {
    console.log(`Cleaning up ${leftoverTemp.length} unmapped temp departments...`);
    for (const d of leftoverTemp) {
      await prisma.department.delete({ where: { id: d.id } });
    }
  }

  const finalCount = await prisma.department.count();
  console.log(`Department synchronization complete! Total active departments: ${finalCount}`);
  process.exit(0);
}

syncDepartments().catch((err) => {
  console.error('syncDepartments error:', err);
  process.exit(1);
});
